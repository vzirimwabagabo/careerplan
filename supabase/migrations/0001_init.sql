-- --------------------------------------------------------------------------
-- access policies
--
-- The tracker runs without user accounts, so the published key must be able to
-- read and write these tables. Row level security stays ON (rather than being
-- disabled) so the access is explicit and can be tightened later by replacing
-- these policies with owner-scoped ones.
-- --------------------------------------------------------------------------
alter table settings       enable row level security;
alter table journey        enable row level security;
alter table experiences    enable row level security;
alter table strengths      enable row level security;
alter table actions_702010 enable row level security;
alter table career_stages  enable row level security;
alter table skills         enable row level security;
alter table goals          enable row level security;
alter table first90        enable row level security;
alter table support        enable row level security;
alter table reviews        enable row level security;
alter table activity       enable row level security;

do $$
declare
    tbl text;
begin
    foreach tbl in array array[
        'settings', 'journey', 'experiences', 'strengths', 'actions_702010',
        'career_stages', 'skills', 'goals', 'first90', 'support', 'reviews',
        'activity'
    ] loop
        -- Created only when absent, so re-running the file changes nothing.
        if not exists (
            select 1
            from pg_policies p
            where p.schemaname = 'public'
              and p.tablename = tbl
              and p.policyname = 'shared_access'
        ) then
            execute format(
                'create policy shared_access on %I for all to anon using (true) with check (true)',
                tbl
            );
        end if;
        execute format('grant all on table %I to anon', tbl);
    end loop;
end $$;

